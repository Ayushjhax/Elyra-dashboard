import "server-only";

import { serviceClient } from "@/lib/supabase/server";
import type {
  PredictionSignalRecord,
  PredictionTechnicalSignal,
  SignalStatus,
} from "@/lib/prediction/signal-types";

/* ---------------------------------------------------------------------------
   Storing signals, and tracking what became of them.

   ── Forward tracking is not a backtest ─────────────────────────────────

   Two win rates exist in this system and they must never be pooled:

     HISTORICAL   simulated over past probability series, one success
                  definition, a stated universe — `signal-backtest.ts`;

     FORWARD      what actually happened to signals this deployment issued,
                  tracked here.

   They answer different questions and have different biases. The historical
   figure is clean but assumes fills that never happened; the forward figure
   is real but starts at n=0 and only grows. Averaging them produces a number
   that describes neither, so they are stored, computed and rendered
   separately, and nothing in this file can read the other one.

   Paper only. Nothing here places an order.

   ── Tenancy ───────────────────────────────────────────────────────────

   `serviceClient()` bypasses RLS, so `.eq("user_id", …)` IS the tenant
   boundary. Every read below carries one, and the one that does not —
   `openSignals` — is the lifecycle worker's, which is deliberately global and
   returns no user data to any caller.
--------------------------------------------------------------------------- */

interface Row {
  id: string;
  user_id: string | null;
  market_id: string;
  condition_id: string | null;
  token_id: string;
  strategy_id: string;
  strategy_version: string;
  direction: string;
  strength: string;
  signal: PredictionTechnicalSignal;
  status: SignalStatus;
  entry_filled_at: string | null;
  entry_price: number | null;
  resolved_at: string | null;
  result_points: number | null;
  generated_at: string;
  expires_at: string | null;
  updated_at: string;
}

function toRecord(row: Row): PredictionSignalRecord {
  return {
    id: row.id,
    userId: row.user_id,
    signal: row.signal,
    status: row.status,
    entryFilledAt: row.entry_filled_at,
    entryPrice: row.entry_price,
    resolvedAt: row.resolved_at,
    resultPoints: row.result_points,
    createdAt: row.generated_at,
    updatedAt: row.updated_at,
  };
}

/**
 * Persists a generated signal.
 *
 * Returns the stored id, or null when the table is missing or the write
 * failed. Null is handled by every caller as "not tracked" — a signal that
 * could not be stored is still a valid signal to look at, it just cannot have
 * an alert attached to it.
 */
export async function saveSignal(input: {
  userId: string | null;
  signal: PredictionTechnicalSignal;
}): Promise<string | null> {
  const { signal } = input;

  const { data, error } = await serviceClient()
    .from("prediction_signals")
    .insert({
      user_id: input.userId,
      market_id: signal.marketId,
      condition_id: signal.conditionId,
      token_id: signal.tokenId,
      strategy_id: signal.strategyId,
      strategy_version: signal.strategyVersion,
      direction: signal.direction,
      strength: signal.strength,
      signal,
      /* An actionable setup starts WAITING for its entry. A watch or neutral
         read has nothing to wait for and is simply recorded. */
      status:
        signal.direction === "long_yes" ||
        signal.direction === "long_no" ||
        signal.direction === "long_outcome"
          ? "waiting_entry"
          : "generated",
      generated_at: signal.generatedAt,
      expires_at: signal.expiresAt,
    })
    .select("id")
    .single();

  if (error !== null || data === null) return null;
  return data.id as string;
}

/** One signal, scoped to its owner. */
export async function getSignal(
  id: string,
  userId: string,
): Promise<PredictionSignalRecord | null> {
  const { data, error } = await serviceClient()
    .from("prediction_signals")
    .select("*")
    .eq("id", id)
    /* A signal with no user_id was generated by a scan and is public; one
       with a user_id belongs to that user alone. */
    .or(`user_id.eq.${userId},user_id.is.null`)
    .maybeSingle();

  if (error !== null || data === null) return null;
  return toRecord(data as Row);
}

/** A user's signal history, newest first. */
export async function listSignals(
  userId: string,
  limit = 20,
): Promise<PredictionSignalRecord[]> {
  const { data, error } = await serviceClient()
    .from("prediction_signals")
    .select("*")
    .eq("user_id", userId)
    .order("generated_at", { ascending: false })
    .limit(Math.min(Math.max(limit, 1), 100));

  if (error !== null || data === null) return [];
  return (data as Row[]).map(toRecord);
}

/**
 * Every signal still being tracked, across all users.
 *
 * The lifecycle worker's query. Returns the signal payload and its status and
 * nothing that identifies a person, because the worker has no business
 * knowing whose setup it is watching.
 */
export async function openSignals(limit = 200): Promise<PredictionSignalRecord[]> {
  const { data, error } = await serviceClient()
    .from("prediction_signals")
    .select("*")
    .in("status", ["generated", "waiting_entry", "entered"])
    .order("generated_at", { ascending: true })
    .limit(limit);

  if (error !== null || data === null) return [];
  return (data as Row[]).map(toRecord);
}

export async function updateSignalStatus(
  id: string,
  patch: {
    status: SignalStatus;
    entryFilledAt?: string | null;
    entryPrice?: number | null;
    resolvedAt?: string | null;
    resultPoints?: number | null;
  },
): Promise<boolean> {
  const { error } = await serviceClient()
    .from("prediction_signals")
    .update({
      status: patch.status,
      ...(patch.entryFilledAt !== undefined ? { entry_filled_at: patch.entryFilledAt } : {}),
      ...(patch.entryPrice !== undefined ? { entry_price: patch.entryPrice } : {}),
      ...(patch.resolvedAt !== undefined ? { resolved_at: patch.resolvedAt } : {}),
      ...(patch.resultPoints !== undefined ? { result_points: patch.resultPoints } : {}),
      updated_at: new Date().toISOString(),
    })
    .eq("id", id);

  return error === null;
}

/* ---------------------------------------------------------------------------
   Lifecycle transitions
--------------------------------------------------------------------------- */

export interface LifecycleObservation {
  /** Current best ask on the traded outcome — what an entry would pay. */
  ask: number | null;
  /** Current best bid — what an exit would receive. */
  bid: number | null;
  now?: number;
}

export interface LifecycleTransition {
  status: SignalStatus;
  reason: string;
  entryPrice?: number;
  resultPoints?: number;
}

/**
 * What one observation does to one tracked signal.
 *
 * Pure, so the whole lifecycle is testable without a database or a venue.
 * Returns null when nothing changed, which is the common case and must not
 * produce a write or a notification.
 *
 * ── Entry is measured against the ask, exits against the bid ───────────
 *
 * A long enters by paying the ask and leaves by hitting the bid. Using the
 * midpoint for both would record entries that never filled and targets that
 * were never reachable — on a 2¢ spread that is the whole edge of a typical
 * setup.
 */
export function evaluateLifecycle(
  record: PredictionSignalRecord,
  observation: LifecycleObservation,
): LifecycleTransition | null {
  const now = observation.now ?? Date.now();
  const { signal } = record;

  const expiresAt = signal.expiresAt === null ? null : Date.parse(signal.expiresAt);

  if (record.status === "waiting_entry" || record.status === "generated") {
    /* Expiry only applies BEFORE entry. Once filled, the position is live and
       the signal's own TTL — which bounds how long the read stays current —
       no longer governs it. */
    if (expiresAt !== null && now > expiresAt) {
      return { status: "expired", reason: "The entry window passed without the setup triggering." };
    }

    const ask = observation.ask;
    if (ask === null) return null;

    const zoneMax = signal.entry.maxPrice ?? signal.entry.price;
    if (zoneMax === undefined) return null;

    if (ask <= zoneMax) {
      return {
        status: "entered",
        reason: `Entry triggered: the ask reached ${(ask * 100).toFixed(1)}¢, inside the entry zone.`,
        entryPrice: ask,
      };
    }

    return null;
  }

  if (record.status === "entered") {
    const bid = observation.bid;
    if (bid === null) return null;

    const entry = record.entryPrice ?? signal.entry.maxPrice ?? signal.entry.price ?? null;
    if (entry === null) return null;

    const stop = signal.stop.price;
    const target = signal.target.price ?? signal.target.maxPrice;

    /* Invalidation is checked FIRST. When one observation satisfies both — a
       gap through the target and back, or a wide bid/ask straddling them —
       the pessimistic reading is the honest one. The optimistic order
       inflates every forward win rate and is indistinguishable from skill. */
    if (stop !== undefined && bid <= stop) {
      return {
        status: "invalidated",
        reason: `Invalidated: the bid fell to ${(bid * 100).toFixed(1)}¢, at or below the ${(stop * 100).toFixed(1)}¢ level.`,
        resultPoints: (bid - entry) * 100,
      };
    }

    if (target !== undefined && bid >= target) {
      return {
        status: "target_hit",
        reason: `Target reached: the bid is ${(bid * 100).toFixed(1)}¢, at or above ${(target * 100).toFixed(1)}¢.`,
        resultPoints: (bid - entry) * 100,
      };
    }

    return null;
  }

  return null;
}

/* ---------------------------------------------------------------------------
   Forward track record
--------------------------------------------------------------------------- */

export interface ForwardRecord {
  entered: number;
  targetHit: number;
  invalidated: number;
  expiredWithoutEntry: number;
  /** Over DECIDED trades only. Null below the reporting floor. */
  winRatePct: number | null;
  averageResultPoints: number | null;
  /** Always stated, so this can never be read as the backtested figure. */
  basis: string;
}

/** Signals must be decided before a forward rate is worth showing. */
export const FORWARD_MIN_SAMPLE = 20;

export async function forwardRecord(userId: string): Promise<ForwardRecord> {
  const { data, error } = await serviceClient()
    .from("prediction_signals")
    .select("status, result_points")
    .eq("user_id", userId)
    .in("status", ["entered", "target_hit", "invalidated", "expired"]);

  const rows = error !== null || data === null
    ? []
    : (data as Array<{ status: SignalStatus; result_points: number | null }>);

  const targetHit = rows.filter((row) => row.status === "target_hit").length;
  const invalidated = rows.filter((row) => row.status === "invalidated").length;
  const entered = rows.filter((row) => row.status === "entered").length + targetHit + invalidated;
  const expired = rows.filter((row) => row.status === "expired").length;

  const decided = targetHit + invalidated;
  const points = rows
    .map((row) => row.result_points)
    .filter((value): value is number => value !== null);

  return {
    entered,
    targetHit,
    invalidated,
    expiredWithoutEntry: expired,
    winRatePct: decided >= FORWARD_MIN_SAMPLE ? (targetHit / decided) * 100 : null,
    averageResultPoints:
      points.length > 0 ? points.reduce((total, value) => total + value, 0) / points.length : null,
    basis:
      "Forward paper tracking of signals this deployment issued. Separate from, " +
      "and never combined with, the historical backtested win rate.",
  };
}
